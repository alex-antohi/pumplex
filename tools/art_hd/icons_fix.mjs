const grids = {};
for (const [name, txt] of Object.entries(ICONS)) {
  const rows = txt.trim().split('\n');
  if (rows.length !== 48 || rows.some(r => r.length !== 48 || /[^#.]/.test(r))) throw new Error(name + ': grid must be 48 x 48');
  grids[name] = rows.map(r => [...r].map(ch => ch === '#'));
}
const names = Object.keys(grids);
for (const n of names) {
  const g = grids[n];
  const buf = png(48, 48, (x, y) => g[y][x] ? [255, 255, 255, 255] : [0, 0, 0, 0]);
  for (const d of ['', '2.0x', '3.0x']) {
    const dir = path.join(ROOT, 'assets', 'icons', d);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, n + '.png'), buf);
  }
}

// Preview: 4x on dark purple (8 per row), then each icon box-filtered to 24 px (1x) and shown at 3x.
const BG = [38, 20, 72], PAD = 12, S4 = 192, S1 = 72;
const perRow = 8, rowsA = Math.ceil(names.length / perRow);
const W = PAD + perRow * (S4 + PAD), H = PAD + rowsA * (S4 + PAD) + (S1 + PAD);
const cover = (g, x, y) => { let n = 0; for (let j = 0; j < 2; j++) for (let i = 0; i < 2; i++) n += g[y * 2 + j][x * 2 + i] ? 1 : 0; return n / 4; };
const prev = png(W, H, (x, y) => {
  const aH = PAD + rowsA * (S4 + PAD);
  if (y < aH) {
    const c = Math.floor((x - PAD) / (S4 + PAD)), r = Math.floor((y - PAD) / (S4 + PAD));
    const lx = x - PAD - c * (S4 + PAD), ly = y - PAD - r * (S4 + PAD), i = r * perRow + c;
    if (c < 0 || r < 0 || lx < 0 || lx >= S4 || ly < 0 || ly >= S4 || i >= names.length) return [...BG, 255];
    return grids[names[i]][Math.floor(ly / 4)][Math.floor(lx / 4)] ? [255, 255, 255, 255] : [...BG, 255];
  }
  const ly = y - aH - PAD / 2, lc = Math.floor((x - PAD) / (24 * 3 + 12)), lx = x - PAD - lc * (24 * 3 + 12);
  if (lc < 0 || lc >= names.length || lx >= 72 || ly < 0 || ly >= 72) return [...BG, 255];
  const v = cover(grids[names[lc]], Math.floor(lx / 3), Math.floor(ly / 3));
  return [Math.round(BG[0] + (255 - BG[0]) * v), Math.round(BG[1] + (255 - BG[1]) * v), Math.round(BG[2] + (255 - BG[2]) * v), 255];
});
fs.writeFileSync(path.join(ROOT, 'tools', 'art_hd', 'preview_icons_fix.png'), prev);
console.log('wrote', names.length, 'icons x 3 folders + preview');
